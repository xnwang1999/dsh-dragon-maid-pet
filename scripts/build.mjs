import { readFile, writeFile } from 'node:fs/promises';
import { STAGES } from '../logic.js';
const root = new URL('../', import.meta.url);
const [logic, artwork, reasoning, body] = await Promise.all(['logic.js','artwork.js','reasoning-effort.js','client-body.js'].map(name=>readFile(new URL(name,root),'utf8')));
const embedded = {};
for (const character of ['dragon','claude','deepseek']) {
  embedded[character] = {};
  for (const stage of STAGES) {
    const ext = character === 'dragon' ? 'png' : 'webp';
    const png = await readFile(new URL(character === 'dragon' ? `assets/${stage}.png` : `assets/${character}/${stage}.webp`,root)).catch(()=>null);
    if (png) embedded[character][stage] = `data:image/${ext};base64,${png.toString('base64')}`;
  }
}
const compiled = `// Generated by scripts/build.mjs. All displayed artwork is self-contained.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-dragon-maid-pet',\n  factory(require) {\nconst EMBEDDED_IMAGES = ${JSON.stringify(embedded)};\n${logic.replace(/^export /gm,'')}\n${artwork.replace(/^export /gm,'')}\n${reasoning.replace(/^export /gm,'')}\n${body}\n  }\n});\n`;
await writeFile(new URL('client.js',root),compiled,'utf8');
console.log(`Built dsh-dragon-maid-pet: ${Object.values(embedded).reduce((n,set)=>n+Object.keys(set).length,0)} embedded PNG illustrations across ${Object.keys(embedded).length} characters.`);
